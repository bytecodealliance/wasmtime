/// Maximum number of WIT packages generated by `wit-smith`.
const MAX_PACKAGES: usize = 4;

/// Maximum size of each type generated by `wit-smith`.
const MAX_TYPE_SIZE: usize = 20;

/// Maximum number of items in a world generated by this fuzzer, not counting
/// the items which are implicitly added for dependencies between interfaces.
const MAX_WORLD_ITEMS: u32 = 16;

/// Maximum number of calls to exported functions per test case.
const MAX_CALLS: usize = 20;

/// Labels to import and export interfaces under, and names of functions
/// directly imported and exported by worlds. These are drawn from a small set
/// to also generate the same label for an import and an export.
const LABELS: &[&str] = &["a", "b", "c", "my-label", "x-y-z", "label2"];

/// Signatures of functions directly imported and exported by worlds.
const FUNC_SIGNATURES: &[&str] = &[
    "()",
    "(a: u32) -> u32",
    "(a: string, b: list<u8>) -> string",
    "(a: f64, b: char, c: bool) -> tuple<s8, u64>",
    "(a: list<string>) -> option<result<u16, s32>>",
];

/// Runs a single test case of this fuzzer with the input `u`.
pub fn component_implements(u: &mut Unstructured<'_>) -> arbitrary::Result<()> {
    run(u).map(drop)
}

/// Statistics about what a single test case exercised, used to check that the
/// fuzzer eventually explores interesting cases.
#[derive(Default, Debug)]
#[cfg_attr(not(test), expect(dead_code, reason = "only read in tests"))]
struct Stats {
    labelled_imports: usize,
    labelled_exports: usize,
    external_ids: usize,
    resources: usize,
    exported_resources: usize,
    calls_through_labels: usize,
    calls_to_stubs: usize,
    wrapped: bool,
}

fn run(u: &mut Unstructured<'_>) -> arbitrary::Result<Stats> {
    crate::init_fuzzing();

    let config: generators::Config = u.arbitrary()?;
    let canonical_names: bool = u.arbitrary()?;
    let (resolve, world) = gen_world(u)?;
    test_world(u, config, resolve, world, canonical_names)
}

/// Tests a component implementing `world`, using `u` for all remaining
/// choices.
fn test_world(
    u: &mut Unstructured<'_>,
    mut config: generators::Config,
    mut resolve: Resolve,
    world: WorldId,
    canonical_names: bool,
) -> arbitrary::Result<Stats> {
    assign_external_ids(u, &mut resolve, world)?;
    log_world(&resolve, world);
    let model = Model::new(&resolve, world, canonical_names);

    let mangling = if u.arbitrary()? {
        ManglingAndAbi::Standard32
    } else {
        ManglingAndAbi::Legacy(LiftLowerAbi::Sync)
    };
    let mut guest = Guest::generate(u, &model, mangling)?;
    let Some(mut wasm) = componentize(&model, &guest.module, u.arbitrary()?) else {
        return Err(arbitrary::Error::IncorrectFormat);
    };

    // Optionally nest the component within another one which instantiates it
    // and re-exports its exports, possibly passing its imports for the labels
    // of an interface to the nested component under other labels of the same
    // interface.
    let wrapped = u.arbitrary()?;
    if wrapped {
        let args = permute_labels(u, &model, &wasm)?;
        log::debug!("wrapping the component with arguments {args:?}");
        wasm = wrap(&wasm, &args);
        guest.route_through(&model, &args);
    }
    log_wasm(&wasm);

    let engine = engine(u, &mut config, canonical_names)?;
    let component = match Component::new(&engine, &wasm) {
        Ok(component) => component,
        Err(e) => panic!("failed to compile component: {e:?}"),
    };
    model.check_component(&engine, &component);

    // Optionally round-trip the component through serialization, checking that
    // the deserialized component has the same metadata, and keep testing with
    // the deserialized component.
    let component = if u.arbitrary()? {
        let bytes = component.serialize().unwrap();
        // SAFETY: these bytes were just produced by `serialize` with the same
        // engine.
        let component = unsafe { Component::deserialize(&engine, &bytes).unwrap() };
        model.check_component(&engine, &component);
        component
    } else {
        component
    };

    let host = Host::new(&model);
    let linker = host.linker(&engine, None, false).unwrap();
    host.check_substituted_type(&engine, &linker, &component);
    host.check_missing_import(u, &engine, &component)?;

    let mut store = Store::new(&engine, HostState::default());
    config.configure_store_epoch_and_fuel(&mut store);
    let instance = match linker.instantiate(&mut store, &component) {
        Ok(instance) => instance,
        Err(e) => panic!("failed to instantiate component: {e:?}"),
    };
    let exported_resources = model.check_instance(&mut store, &instance, &host);
    let (calls_through_labels, _) =
        guest.call_forwarders(u, &mut store, &instance, &model, None)?;

    // Free up this instance's resources, such as pooling allocator slots, for
    // the instance created by the next check.
    drop(store);
    let calls_to_stubs = host.check_unknown_imports(u, &config, &engine, &component, &guest)?;

    Ok(Stats {
        labelled_imports: model
            .imports
            .iter()
            .filter(|i| i.implements.is_some())
            .count(),
        labelled_exports: model
            .exports
            .iter()
            .filter(|i| i.implements.is_some())
            .count(),
        external_ids: model
            .imports
            .iter()
            .chain(&model.exports)
            .filter(|i| i.external_id.is_some())
            .count(),
        resources: host.payloads.len(),
        exported_resources,
        calls_through_labels,
        calls_to_stubs,
        wrapped,
    })
}

/// Generates WIT packages with `wit-smith` and selects or generates a world
/// within them.
fn gen_world(u: &mut Unstructured<'_>) -> arbitrary::Result<(Resolve, WorldId)> {
    let mut config: wit_smith::Config = u.arbitrary()?;
    config.max_packages = config.max_packages.min(MAX_PACKAGES);
    config.max_type_size = config.max_type_size.min(MAX_TYPE_SIZE);
    // Async functions and async types are not the focus of this fuzzer and
    // would require the async ABI in the guest.
    config.async_ = false;
    config.futures = false;
    config.streams = false;
    config.error_context = false;
    config.fixed_length_lists = false;
    // Generate labelled imports and exports in `wit-smith`'s worlds too.
    config.implements = true;
    // This only affects how `wit-smith` encodes the WIT package, canonical
    // names are randomly used for the component below.
    config.canonical_names = false;
    let wasm = wit_smith::smith(&config, u)?;
    let mut resolve = match wit_component::decode(&wasm).unwrap() {
        DecodedWasm::WitPackage(resolve, _) => resolve,
        DecodedWasm::Component(..) => unreachable!(),
    };

    let interfaces = resolve
        .interfaces
        .iter()
        .filter(|(_, i)| i.name.is_some() && i.package.is_some())
        .map(|(id, _)| id)
        .collect::<Vec<_>>();
    let worlds = resolve.worlds.iter().map(|(id, _)| id).collect::<Vec<_>>();

    if worlds.is_empty() || (!interfaces.is_empty() && u.ratio(3, 4)?) {
        if interfaces.is_empty() {
            return Err(arbitrary::Error::IncorrectFormat);
        }
        let wit = gen_world_wit(u, &resolve, &interfaces)?;
        log::debug!("generated world:\n{wit}");
        let pkg = match resolve.push_source("world.wit", &wit) {
            Ok(pkg) => pkg,
            Err(e) => {
                log::debug!("generated world is invalid: {e:?}");
                return Err(arbitrary::Error::IncorrectFormat);
            }
        };
        let world = resolve.packages[pkg].worlds["w"];
        Ok((resolve, world))
    } else {
        Ok((resolve, *u.choose(&worlds)?))
    }
}

/// Generates the WIT source of a package with a world `w` which imports and
/// exports some of the `interfaces` both by their own name and under labels,
/// along with some functions.
fn gen_world_wit(
    u: &mut Unstructured<'_>,
    resolve: &Resolve,
    interfaces: &[InterfaceId],
) -> arbitrary::Result<String> {
    let mut items = Vec::new();
    let mut import_names = HashSet::new();
    let mut export_names = HashSet::new();
    let mut plain_imports = HashSet::new();
    let mut plain_exports = HashSet::new();
    let mut used = Vec::new();

    for _ in 0..u.int_in_range(0..=MAX_WORLD_ITEMS)? {
        let import = u.arbitrary()?;
        let (dir, names, plain) = if import {
            ("import", &mut import_names, &mut plain_imports)
        } else {
            ("export", &mut export_names, &mut plain_exports)
        };

        // Favor interfaces which are already part of this world to get
        // several labels for the same interface.
        let iface = if !used.is_empty() && u.arbitrary()? {
            *u.choose(&used)?
        } else {
            *u.choose(interfaces)?
        };

        match u.int_in_range(0..=5)? {
            // An interface under a label, possibly the name of the interface
            // itself.
            0..=2 => {
                let label = if u.ratio(1, 4)? {
                    resolve.interfaces[iface].name.clone().unwrap()
                } else {
                    u.choose(LABELS)?.to_string()
                };
                if !names.insert(label.clone()) {
                    continue;
                }
                items.push(format!(
                    "{dir} %{label}: {};",
                    interface_path(resolve, iface)
                ));
                used.push(iface);
            }

            // An interface by its own name.
            3..=4 => {
                if !plain.insert(iface) {
                    continue;
                }
                items.push(format!("{dir} {};", interface_path(resolve, iface)));
                used.push(iface);
            }

            // A function.
            _ => {
                let name = u.choose(LABELS)?;
                if !names.insert(name.to_string()) {
                    continue;
                }
                let sig = u.choose(FUNC_SIGNATURES)?;
                items.push(format!("{dir} %{name}: func{sig};"));
            }
        }
    }

    Ok(format!(
        "package implements-fuzz:worlds;\n\nworld w {{\n{}\n}}\n",
        items.join("\n")
    ))
}

/// Logs the WIT of all packages, with the package of `world` first.
fn log_world(resolve: &Resolve, world: WorldId) {
    if !log::log_enabled!(log::Level::Debug) {
        return;
    }
    let pkg = resolve.worlds[world].package.unwrap();
    let nested = resolve
        .packages
        .iter()
        .map(|(id, _)| id)
        .filter(|id| *id != pkg)
        .collect::<Vec<_>>();
    let mut printer = wit_component::WitPrinter::default();
    match printer.print(resolve, pkg, &nested) {
        Ok(()) => log::debug!(
            "testing world `{}` in:\n{}",
            resolve.worlds[world].name,
            printer.output
        ),
        Err(e) => log::debug!("failed to print WIT: {e:?}"),
    }
}

/// Returns the WIT path of the interface `id`, e.g. `%ns:%pkg/%iface@1.0.0`.
fn interface_path(resolve: &Resolve, id: InterfaceId) -> String {
    let iface = &resolve.interfaces[id];
    let pkg = &resolve.packages[iface.package.unwrap()].name;
    let mut path = format!(
        "%{}:%{}/%{}",
        pkg.namespace,
        pkg.name,
        iface.name.as_ref().unwrap()
    );
    if let Some(version) = &pkg.version {
        path.push_str(&format!("@{version}"));
    }
    path
}

/// Assigns a distinct `external-id`, or none, to all functions and types of
/// all interfaces and to all items of `world`.
fn assign_external_ids(
    u: &mut Unstructured<'_>,
    resolve: &mut Resolve,
    world: WorldId,
) -> arbitrary::Result<()> {
    fn gen_id(u: &mut Unstructured<'_>, n: &mut u32) -> arbitrary::Result<Option<String>> {
        if !u.arbitrary()? {
            return Ok(None);
        }
        *n += 1;
        // Some external IDs look like interface names to try to confuse them
        // with `implements`.
        Ok(Some(match u.int_in_range(0..=2)? {
            0 => format!("id-{n}"),
            1 => format!("x:y/z@1.0.{n}"),
            _ => format!("ext {n} 🏷️ {}", u.arbitrary::<&str>()?),
        }))
    }

    let mut n = 0;
    for (_, iface) in resolve.interfaces.iter_mut() {
        for func in iface.functions.values_mut() {
            func.external_id = gen_id(u, &mut n)?;
        }
    }
    for (_, ty) in resolve.types.iter_mut() {
        ty.external_id = gen_id(u, &mut n)?;
    }
    let world = &mut resolve.worlds[world];
    for item in world.imports.values_mut().chain(world.exports.values_mut()) {
        match item {
            WorldItem::Interface { external_id, .. } => *external_id = gen_id(u, &mut n)?,
            WorldItem::Function(func) => func.external_id = gen_id(u, &mut n)?,
            // Types were handled above.
            WorldItem::Type { .. } => {}
        }
    }
    Ok(())
}

/// What's expected of a component created for a world.
struct Model<'a> {
    resolve: &'a Resolve,
    world: WorldId,
    imports: Vec<Item<'a>>,
    exports: Vec<Item<'a>>,
    /// All functions imported by the world, in the order the guest imports
    /// them. Indices into this list identify host functions.
    import_funcs: Vec<FuncRef<'a>>,
    canonical_names: bool,
}

/// An import or export of a world.
struct Item<'a> {
    key: &'a WorldKey,
    item: &'a WorldItem,
    /// Name of this item in the component.
    name: String,
    /// The interface this item implements and its name in the component.
    implements: Option<(InterfaceId, String)>,
    external_id: Option<&'a str>,
}

/// A function imported or exported by a world, either directly or through the
/// interface at `key`.
#[derive(Clone, Copy)]
struct FuncRef<'a> {
    key: Option<&'a WorldKey>,
    func: &'a WitFunction,
}

impl<'a> Model<'a> {
    fn new(resolve: &'a Resolve, world: WorldId, canonical_names: bool) -> Self {
        let w = &resolve.worlds[world];
        let item = |(key, item): (&'a WorldKey, &'a WorldItem)| Item {
            key,
            item,
            name: if canonical_names {
                resolve.name_canonicalized_world_key(key)
            } else {
                resolve.name_world_key(key)
            },
            implements: resolve.implements_interface(key, item).map(|id| {
                let name = if canonical_names {
                    resolve.canonicalized_id_of(id)
                } else {
                    resolve.id_of(id)
                };
                (id, name.unwrap())
            }),
            external_id: match item {
                WorldItem::Interface { external_id, .. } => external_id.as_deref(),
                WorldItem::Function(f) => f.external_id.as_deref(),
                WorldItem::Type { id, .. } => resolve.types[*id].external_id.as_deref(),
            },
        };

        let mut import_funcs = Vec::new();
        for (key, item) in w.imports.iter() {
            match item {
                WorldItem::Function(func) => import_funcs.push(FuncRef { key: None, func }),
                WorldItem::Interface { id, .. } => {
                    for func in resolve.interfaces[*id].functions.values() {
                        import_funcs.push(FuncRef {
                            key: Some(key),
                            func,
                        });
                    }
                }
                WorldItem::Type { .. } => {}
            }
        }

        Model {
            resolve,
            world,
            imports: w.imports.iter().map(item).collect(),
            exports: w.exports.iter().map(item).collect(),
            import_funcs,
            canonical_names,
        }
    }

    fn import(&self, name: &str) -> Option<&Item<'a>> {
        self.imports.iter().find(|i| i.name == name)
    }

    fn export_by_key(&self, key: &WorldKey) -> Option<&Item<'a>> {
        self.exports.iter().find(|i| i.key == key)
    }

    /// Returns a description of the import function `i` for error messages.
    fn describe_import_func(&self, i: usize) -> String {
        let f = &self.import_funcs[i];
        match f.key {
            Some(key) => format!("`{}#{}`", self.resolve.name_world_key(key), f.func.name),
            None => format!("`{}`", f.func.name),
        }
    }

    /// Returns the import which the import function `i` belongs to.
    fn import_of_func(&self, i: usize) -> &Item<'a> {
        let f = &self.import_funcs[i];
        self.imports
            .iter()
            .find(|i| match f.key {
                Some(key) => i.key == key,
                None => matches!(i.item, WorldItem::Function(func) if std::ptr::eq(func, f.func)),
            })
            .unwrap()
    }

    /// Checks the reflection of `component` against this model.
    fn check_component(&self, engine: &Engine, component: &Component) {
        let ty = component.component_type();
        self.check_externs(engine, "import", ty.imports(engine), &self.imports);
        self.check_externs(engine, "export", ty.exports(engine), &self.exports);

        // `Component::get_export{,_index}` must agree with the component type.
        for (name, ext) in ty.exports(engine) {
            let index = component
                .get_export_index(None, name)
                .unwrap_or_else(|| panic!("export `{name}` not found by `get_export_index`"));
            let (item, _) = component
                .get_export(None, name)
                .unwrap_or_else(|| panic!("export `{name}` not found by `get_export`"));
            assert_same_kind(name, &item, &ext.ty);
            if let ComponentItem::ComponentInstance(instance) = &ext.ty {
                for (nested, nested_ext) in instance.exports(engine) {
                    assert!(
                        component.get_export_index(Some(&index), nested).is_some(),
                        "export `{name}#{nested}` not found by `get_export_index`"
                    );
                    let (item, _) =
                        component
                            .get_export(Some(&index), nested)
                            .unwrap_or_else(|| {
                                panic!("export `{name}#{nested}` not found by `get_export`")
                            });
                    assert_same_kind(nested, &item, &nested_ext.ty);
                }
            }
        }

        // Labelled exports can't be found under the name of the interface
        // they implement.
        for export in &self.exports {
            let Some((iface, implements)) = &export.implements else {
                continue;
            };
            if self.export_by_key(&WorldKey::Interface(*iface)).is_some() {
                continue;
            }
            for name in [implements.clone(), self.resolve.id_of(*iface).unwrap()] {
                assert!(
                    component.get_export_index(None, name.as_str()).is_none(),
                    "`{name}` was found as an export but only `{}` implements it",
                    export.name,
                );
            }
        }
    }

    /// Checks that the imports or exports `actual` of a component match the
    /// imports or exports `expected` of the world.
    fn check_externs<'b>(
        &self,
        engine: &Engine,
        desc: &str,
        actual: impl Iterator<Item = (&'b str, ComponentExtern<'b>)>,
        expected: &[Item<'_>],
    ) {
        let mut seen = HashSet::new();
        for (name, ext) in actual {
            let item = expected
                .iter()
                .find(|i| i.name == name)
                .unwrap_or_else(|| panic!("unexpected {desc} `{name}`"));
            assert!(seen.insert(name), "duplicate {desc} `{name}`");
            assert_eq!(
                ext.implements,
                item.implements.as_ref().map(|(_, s)| s.as_str()),
                "wrong `implements` for {desc} `{name}`"
            );
            assert_eq!(
                ext.external_id, item.external_id,
                "wrong `external-id` for {desc} `{name}`"
            );
            self.check_is_implements(desc, item, &ext);

            match (item.item, &ext.ty) {
                (WorldItem::Interface { id, .. }, ComponentItem::ComponentInstance(instance)) => {
                    self.check_instance_type(engine, desc, name, *id, instance);
                }
                (WorldItem::Function(func), ComponentItem::ComponentFunc(ty)) => {
                    check_func_type(desc, name, func, ty);
                }
                (
                    WorldItem::Type { id, .. },
                    ComponentItem::Type(_) | ComponentItem::Resource(_),
                ) => {
                    assert_eq!(
                        is_resource(self.resolve, *id),
                        matches!(ext.ty, ComponentItem::Resource(_)),
                        "{desc} `{name}` has the wrong kind of type"
                    );
                }
                (item, ty) => panic!("{desc} `{name}` is a {ty:?} but the world has {item:?}"),
            }
        }

        for item in expected {
            assert!(
                !self.is_required(item) || seen.contains(item.name.as_str()),
                "missing {desc} `{}`",
                item.name
            );
        }
    }

    /// Returns whether `item` must be present in the component.
    ///
    /// All items with functions must be present, others may be omitted by
    /// `wit-component` if they're not used.
    fn is_required(&self, item: &Item<'_>) -> bool {
        match item.item {
            WorldItem::Function(_) => true,
            WorldItem::Interface { id, .. } => !self.resolve.interfaces[*id].functions.is_empty(),
            WorldItem::Type { .. } => false,
        }
    }

    /// Checks the exports of the instance type `instance` of the import or
    /// export `name` against the interface `id`.
    fn check_instance_type(
        &self,
        engine: &Engine,
        desc: &str,
        name: &str,
        id: InterfaceId,
        instance: &ComponentInstance,
    ) {
        let iface = &self.resolve.interfaces[id];
        let mut seen = HashSet::new();
        for (nested, ext) in instance.exports(engine) {
            assert!(seen.insert(nested), "duplicate `{name}#{nested}`");
            assert_eq!(
                ext.implements, None,
                "{desc} `{name}#{nested}` has an `implements`"
            );
            let external_id = if let Some(func) = iface.functions.get(nested) {
                match &ext.ty {
                    ComponentItem::ComponentFunc(ty) => {
                        check_func_type(desc, &format!("{name}#{nested}"), func, ty)
                    }
                    ty => panic!("{desc} `{name}#{nested}` should be a function, not {ty:?}"),
                }
                func.external_id.as_deref()
            } else if let Some(ty) = iface.types.get(nested) {
                match &ext.ty {
                    ComponentItem::Type(_) | ComponentItem::Resource(_) => assert_eq!(
                        is_resource(self.resolve, *ty),
                        matches!(ext.ty, ComponentItem::Resource(_)),
                        "{desc} `{name}#{nested}` has the wrong kind of type"
                    ),
                    ty => panic!("{desc} `{name}#{nested}` should be a type, not {ty:?}"),
                }
                self.resolve.types[*ty].external_id.as_deref()
            } else {
                panic!("unexpected export `{nested}` in {desc} `{name}`")
            };
            assert_eq!(
                ext.external_id, external_id,
                "wrong `external-id` for {desc} `{name}#{nested}`"
            );
        }
        for func in iface.functions.keys() {
            assert!(
                seen.contains(func.as_str()),
                "missing `{name}#{func}` in {desc}"
            );
        }
    }

    /// Checks `ComponentExtern::is_implements` for a few names related to the
    /// interface that `item` implements, if any.
    fn check_is_implements(&self, desc: &str, item: &Item<'_>, ext: &ComponentExtern<'_>) {
        let check = |name: &str, expected: bool| {
            assert_eq!(
                ext.is_implements(name),
                expected,
                "`is_implements({name:?})` for {desc} `{}` which implements {:?}",
                item.name,
                item.implements.as_ref().map(|(_, s)| s),
            );
        };

        // An item never implements its own name, which is either a label or
        // an interface without an `implements`.
        check(&item.name, false);

        let Some((iface, implements)) = &item.implements else {
            if let WorldKey::Interface(id) = item.key {
                check(&self.resolve.id_of(*id).unwrap(), false);
            }
            return;
        };
        check(implements, true);

        let name = self.resolve.interfaces[*iface].name.as_ref().unwrap();
        let pkg = &self.resolve.packages[self.resolve.interfaces[*iface].package.unwrap()].name;
        let base = format!("{}:{}/{name}", pkg.namespace, pkg.name);
        check(&format!("{}:{}/{name}x", pkg.namespace, pkg.name), false);

        let Some(v) = &pkg.version else {
            check(&base, true);
            check(&format!("{base}@1.0.0"), false);
            return;
        };

        // The exact version of the interface.
        //
        // FIXME: Wasmtime doesn't keep the `version-suffix` of names, so with
        // canonical names the build metadata of versions which have no
        // semver-compatible track (`0.0.x` and prereleases) is lost and
        // `is_implements` doesn't match the full version, e.g. `(implements
        // "a:b/c@0.0.1") (version-suffix "+abc")` doesn't implement
        // `a:b/c@0.0.1+abc`, whereas `(implements "a:b/c@0.0.1+abc")` does.
        let no_track = !v.pre.is_empty() || (v.major == 0 && v.minor == 0);
        if !(self.canonical_names && no_track && !v.build.is_empty()) {
            check(&format!("{base}@{v}"), true);
        }
        check(&base, false);

        // Semver-compatible and incompatible versions.
        let (major, minor, patch) = (v.major, v.minor, v.patch);
        if !v.pre.is_empty() {
            check(&format!("{base}@{major}.{minor}.{}", patch + 1), false);
        } else if major != 0 {
            check(&format!("{base}@{major}.{}.0", minor + 1), true);
            check(&format!("{base}@{major}.{minor}.{}", patch + 1), true);
            check(&format!("{base}@{}.0.0", major + 1), false);
        } else if minor != 0 {
            check(&format!("{base}@0.{minor}.{}", patch + 1), true);
            check(&format!("{base}@0.{}.0", minor + 1), false);
        } else {
            check(&format!("{base}@0.0.{}", patch + 1), false);
        }
    }

    /// Checks the exports of `instance`, including the resource types of
    /// exported interfaces.
    ///
    /// Returns the number of exported resources which were checked.
    fn check_instance(
        &self,
        store: &mut Store<HostState>,
        instance: &Instance,
        host: &Host<'_>,
    ) -> usize {
        let resolve = self.resolve;

        // Resource types defined by the component, keyed by the export they
        // were found in and the definition of the resource in WIT.
        let mut guest_resources: Vec<((&str, TypeId), ResourceType)> = Vec::new();
        // Resource types of exported interfaces which are defined in other
        // interfaces, checked once all the above resources are known.
        let mut used_resources = Vec::new();

        for export in &self.exports {
            let Some(index) = instance.get_export_index(&mut *store, None, &export.name) else {
                assert!(
                    !self.is_required(export),
                    "export `{}` not found in the instance",
                    export.name
                );
                continue;
            };
            let (item, _) = instance
                .get_export(&mut *store, None, &export.name)
                .unwrap();

            match (export.item, &item) {
                (WorldItem::Function(func), ComponentItem::ComponentFunc(_)) => {
                    let f = instance
                        .get_func(&mut *store, &index)
                        .unwrap_or_else(|| panic!("export `{}` isn't a function", export.name));
                    check_func_type("export", &export.name, func, &f.ty(&*store));
                }
                (WorldItem::Interface { id, .. }, ComponentItem::ComponentInstance(_)) => {
                    let iface = &resolve.interfaces[*id];
                    for func in iface.functions.values() {
                        let name = format!("{}#{}", export.name, func.name);
                        let index = instance
                            .get_export_index(&mut *store, Some(&index), &func.name)
                            .unwrap_or_else(|| panic!("export `{name}` not found"));
                        let f = instance
                            .get_func(&mut *store, &index)
                            .unwrap_or_else(|| panic!("export `{name}` isn't a function"));
                        check_func_type("export", &name, func, &f.ty(&*store));
                    }
                    for (ty_name, ty) in iface.types.iter() {
                        let root = dealias(resolve, *ty);
                        if !is_resource(resolve, root) {
                            continue;
                        }
                        let Some(ty_index) =
                            instance.get_export_index(&mut *store, Some(&index), ty_name)
                        else {
                            continue;
                        };
                        let name = format!("{}#{ty_name}", export.name);
                        let rt = instance
                            .get_resource(&mut *store, &ty_index)
                            .unwrap_or_else(|| panic!("export `{name}` isn't a resource"));
                        match resolve.types[root].owner {
                            // A resource defined by this exported interface,
                            // which must be distinct from all host resources
                            // and from the resources of other exports.
                            TypeOwner::Interface(owner) if owner == *id => {
                                assert!(
                                    host.payloads
                                        .values()
                                        .all(|p| rt != ResourceType::host_dynamic(*p)),
                                    "export `{name}` is a host resource"
                                );
                                let key = (export.name.as_str(), root);
                                match guest_resources.iter().find(|(k, _)| *k == key) {
                                    Some((_, prev)) => assert_eq!(
                                        *prev, rt,
                                        "export `{name}` is a different resource than other \
                                         aliases of it in the same instance"
                                    ),
                                    None => {
                                        for ((other, _), prev) in &guest_resources {
                                            assert!(
                                                *prev != rt,
                                                "export `{name}` is the same resource as one \
                                                 exported by `{other}`"
                                            );
                                        }
                                        guest_resources.push((key, rt));
                                    }
                                }
                            }
                            TypeOwner::Interface(owner) => {
                                used_resources.push((name, root, owner, rt));
                            }
                            TypeOwner::World(_) | TypeOwner::None => unreachable!(),
                        }
                    }
                }
                (item, ty) => panic!(
                    "export `{}` is {ty:?} but the world has {item:?}",
                    export.name
                ),
            }
        }

        // Resources used from other interfaces are either the resources of an
        // exported interface, if it's exported, or those of the host.
        for (name, root, owner, rt) in used_resources {
            let key = WorldKey::Interface(owner);
            let expected = match self.export_by_key(&key) {
                Some(owner) => guest_resources
                    .iter()
                    .find(|(k, _)| *k == (owner.name.as_str(), root))
                    .map(|(_, rt)| *rt),
                None => host
                    .payloads
                    .get(&(Some(key), root))
                    .map(|p| ResourceType::host_dynamic(*p)),
            };
            if let Some(expected) = expected {
                assert_eq!(rt, expected, "wrong resource type for export `{name}`");
            }
        }

        guest_resources.len()
    }
}

/// Asserts that the two items `a` and `b` named `name` are of the same kind.
fn assert_same_kind(name: &str, a: &ComponentItem, b: &ComponentItem) {
    assert_eq!(
        std::mem::discriminant(a),
        std::mem::discriminant(b),
        "`{name}` is both {a:?} and {b:?}"
    );
}

/// Checks the type `ty` of the function `name` against the WIT function `func`.
fn check_func_type(desc: &str, name: &str, func: &WitFunction, ty: &ComponentFunc) {
    let params = ty.params().map(|(name, _)| name).collect::<Vec<_>>();
    let expected = func
        .params
        .iter()
        .map(|p| p.name.as_str())
        .collect::<Vec<_>>();
    assert_eq!(params, expected, "wrong parameters for {desc} `{name}`");
    assert_eq!(
        ty.results().len(),
        usize::from(func.result.is_some()),
        "wrong results for {desc} `{name}`"
    );
}

/// Follows type aliases from `ty` to the type it refers to.
fn dealias(resolve: &Resolve, mut ty: TypeId) -> TypeId {
    while let TypeDefKind::Type(Type::Id(other)) = resolve.types[ty].kind {
        ty = other;
    }
    ty
}

fn is_resource(resolve: &Resolve, ty: TypeId) -> bool {
    matches!(
        resolve.types[dealias(resolve, ty)].kind,
        TypeDefKind::Resource
    )
}

/// The core wasm module implementing a world.
struct Guest<'a> {
    module: Vec<u8>,
    /// Exported functions which forward to an imported function, identified
    /// by its index in `Model::import_funcs`.
    forwarders: Vec<(FuncRef<'a>, usize)>,
    /// For each imported function, the index in `Model::import_funcs` of the
    /// function that calls to it are expected to reach.
    routing: Vec<usize>,
}

impl<'a> Guest<'a> {
    fn generate(
        u: &mut Unstructured<'_>,
        model: &Model<'a>,
        mangling: ManglingAndAbi,
    ) -> arbitrary::Result<Guest<'a>> {
        let resolve = model.resolve;
        let world = &resolve.worlds[model.world];
        let mut sizes = SizeAlign::default();
        if sizes.fill(resolve).is_err() {
            return Err(arbitrary::Error::IncorrectFormat);
        }
        let mut module = CoreModule::default();

        // Imports of WIT functions, all of them so that every function can be
        // forwarded to.
        let mut import_funcs = Vec::new();
        for f in &model.import_funcs {
            let (module_name, name) = resolve.wasm_import_name(
                mangling,
                WasmImport::Func {
                    interface: f.key,
                    func: f.func,
                },
            );
            let sig = resolve.wasm_signature(mangling.import_variant(), f.func);
            let index = module.import(&module_name, &name, &sig.params, &sig.results);
            import_funcs.push((index, sig));
        }

        // Resource intrinsics are optionally imported, which affects whether
        // `wit-component` imports or exports some types. This is decided per
        // resource rather than per import so that labels of the same
        // interface usually have the same type, which `permute_labels` needs.
        let mut drop_resources = HashMap::<TypeId, bool>::new();
        for (key, item) in world.imports.iter() {
            let (interface, types) = match item {
                WorldItem::Interface { id, .. } => (
                    Some(key),
                    resolve.interfaces[*id].types.values().copied().collect(),
                ),
                WorldItem::Type { id, .. } => (None, vec![*id]),
                WorldItem::Function(_) => continue,
            };
            for resource in types {
                if !matches!(resolve.types[resource].kind, TypeDefKind::Resource) {
                    continue;
                }
                let drop = match drop_resources.get(&resource) {
                    Some(drop) => *drop,
                    None => {
                        let drop = u.arbitrary()?;
                        drop_resources.insert(resource, drop);
                        drop
                    }
                };
                if !drop {
                    continue;
                }
                let (module_name, name) = resolve.wasm_import_name(
                    mangling,
                    WasmImport::ResourceIntrinsic {
                        interface,
                        resource,
                        intrinsic: ResourceIntrinsic::ImportedDrop,
                    },
                );
                module.import(&module_name, &name, &[WasmType::I32], &[]);
            }
        }
        for (key, item) in world.exports.iter() {
            let WorldItem::Interface { id, .. } = item else {
                continue;
            };
            for resource in resolve.interfaces[*id].types.values().copied() {
                if !matches!(resolve.types[resource].kind, TypeDefKind::Resource)
                    || !u.arbitrary()?
                {
                    continue;
                }
                for (intrinsic, results) in [
                    (ResourceIntrinsic::ExportedDrop, &[][..]),
                    (ResourceIntrinsic::ExportedNew, &[WasmType::I32][..]),
                    (ResourceIntrinsic::ExportedRep, &[WasmType::I32][..]),
                ] {
                    let (module_name, name) = resolve.wasm_import_name(
                        mangling,
                        WasmImport::ResourceIntrinsic {
                            interface: Some(key),
                            resource,
                            intrinsic,
                        },
                    );
                    module.import(&module_name, &name, &[WasmType::I32], results);
                }
            }
        }

        let realloc = module.define(
            &[WasmType::I32; 4],
            &[WasmType::I32],
            realloc_body(),
            Some(&resolve.wasm_export_name(mangling, WasmExport::Realloc)),
        );

        let mut forwarders = Vec::new();
        for (key, item) in world.exports.iter() {
            let (interface, funcs) = match item {
                WorldItem::Function(func) => (None, vec![func]),
                WorldItem::Interface { id, .. } => (
                    Some(key),
                    resolve.interfaces[*id].functions.values().collect(),
                ),
                WorldItem::Type { .. } => continue,
            };
            for func in funcs {
                let sig = resolve.wasm_signature(mangling.export_variant(), func);
                let candidates = (0..model.import_funcs.len())
                    .filter(|i| {
                        funcs_eq(resolve, func, model.import_funcs[*i].func)
                            && sigs_compatible(&sig, &import_funcs[*i].1)
                    })
                    .collect::<Vec<_>>();
                let target = if !candidates.is_empty() && u.ratio(7, 8)? {
                    Some(*u.choose(&candidates)?)
                } else {
                    None
                };
                let body = match target {
                    Some(i) => {
                        let (index, import_sig) = &import_funcs[i];
                        let retarea = func.result.map(|ty| {
                            (
                                sizes.size(&ty).size_wasm32(),
                                sizes.align(&ty).align_wasm32(),
                            )
                        });
                        forwarder_body(&sig, *index, import_sig, retarea, realloc)
                    }
                    None => unreachable_body(),
                };
                let name = resolve.wasm_export_name(
                    mangling,
                    WasmExport::Func {
                        interface,
                        func,
                        kind: WasmExportKind::Normal,
                    },
                );
                module.define(&sig.params, &sig.results, body, Some(&name));
                if let Some(i) = target {
                    forwarders.push((
                        FuncRef {
                            key: interface,
                            func,
                        },
                        i,
                    ));
                }

                if u.arbitrary()? {
                    let name = resolve.wasm_export_name(
                        mangling,
                        WasmExport::Func {
                            interface,
                            func,
                            kind: WasmExportKind::PostReturn,
                        },
                    );
                    module.define(&sig.results, &[], empty_body(), Some(&name));
                }
            }

            if let WorldItem::Interface { id, .. } = item {
                for resource in resolve.interfaces[*id].types.values().copied() {
                    if !matches!(resolve.types[resource].kind, TypeDefKind::Resource) {
                        continue;
                    }
                    let name = resolve.wasm_export_name(
                        mangling,
                        WasmExport::ResourceDtor {
                            interface: key,
                            resource,
                        },
                    );
                    module.define(&[WasmType::I32], &[], empty_body(), Some(&name));
                }
            }
        }

        if u.arbitrary()? {
            let name = resolve.wasm_export_name(mangling, WasmExport::Initialize);
            module.define(&[], &[], empty_body(), Some(&name));
        }

        let memory = resolve.wasm_export_name(mangling, WasmExport::Memory);
        Ok(Guest {
            module: module.finish(&memory),
            forwarders,
            routing: (0..model.import_funcs.len()).collect(),
        })
    }

    /// Updates the expected routing of calls to imported functions for a
    /// component wrapped by `wrap` with `args`.
    fn route_through(&mut self, model: &Model<'_>, args: &HashMap<String, String>) {
        for (i, routed) in self.routing.iter_mut().enumerate() {
            let import = &model.import_of_func(i).name;
            let Some(outer) = args.get(import) else {
                continue;
            };
            let func = &model.import_funcs[i].func.name;
            *routed = (0..model.import_funcs.len())
                .find(|j| {
                    model.import_of_func(*j).name == *outer
                        && model.import_funcs[*j].func.name == *func
                })
                .unwrap();
        }
    }

    /// Calls the exported functions which forward to an imported function and
    /// checks that the expected import was called with the same arguments and
    /// that its results were returned.
    ///
    /// If `stubbed` is specified then that import was defined with
    /// `Linker::define_unknown_imports_as_*` instead of the host functions of
    /// `Host`, so calls to it are expected to trap or to return default
    /// values.
    ///
    /// Returns the number of calls which went through a labelled import and the
    /// number of calls which went to a stub.
    fn call_forwarders(
        &self,
        u: &mut Unstructured<'_>,
        store: &mut Store<HostState>,
        instance: &Instance,
        model: &Model<'_>,
        stubbed: Option<(&str, Stub)>,
    ) -> arbitrary::Result<(usize, usize)> {
        let mut calls_through_labels = 0;
        let mut calls_to_stubs = 0;
        for (export, import) in self.forwarders.iter().take(MAX_CALLS) {
            let import = &self.routing[*import];
            let (name, func) = match export.key {
                Some(key) => {
                    let name = model.export_by_key(key).unwrap().name.as_str();
                    let index = instance.get_export_index(&mut *store, None, name).unwrap();
                    let index = instance
                        .get_export_index(&mut *store, Some(&index), &export.func.name)
                        .unwrap();
                    let func = instance.get_func(&mut *store, &index).unwrap();
                    (format!("{name}#{}", export.func.name), func)
                }
                None => {
                    let name = export.func.name.as_str();
                    (
                        name.to_string(),
                        instance.get_func(&mut *store, name).unwrap(),
                    )
                }
            };
            let ty = func.ty(&*store);

            let mut fuel = 100;
            let params = ty
                .params()
                .map(|(_, ty)| arbitrary_val(&ty, &mut fuel, u))
                .collect::<arbitrary::Result<Vec<_>>>()?;
            let results = ty
                .results()
                .map(|ty| arbitrary_val(&ty, &mut fuel, u))
                .collect::<arbitrary::Result<Vec<_>>>()?;

            let import_item = model.import_of_func(*import);
            let stub = stubbed.and_then(|(name, stub)| (name == import_item.name).then_some(stub));
            log::debug!(
                "calling `{name}` with {params:?}, which should forward to {} (stub: {stub:?})",
                model.describe_import_func(*import)
            );
            store.data_mut().calls.clear();
            store.data_mut().results = Some(results.clone());
            let mut actual = vec![Val::Bool(false); results.len()];
            let result = func.call(&mut *store, &params, &mut actual);
            let calls = std::mem::take(&mut store.data_mut().calls);
            let called = calls
                .iter()
                .map(|(i, _)| model.describe_import_func(*i))
                .collect::<Vec<_>>();

            match stub {
                None => {
                    if let Err(e) = result {
                        panic!("failed to call export `{name}`: {e:?}");
                    }
                    assert_eq!(
                        calls.iter().map(|(i, _)| *i).collect::<Vec<_>>(),
                        [*import],
                        "export `{name}` should have called {} but called {called:?}",
                        model.describe_import_func(*import),
                    );
                    assert_eq!(
                        calls[0].1, params,
                        "wrong arguments forwarded by export `{name}`"
                    );
                    assert_eq!(actual, results, "wrong results from export `{name}`");
                }
                Some(stub) => {
                    calls_to_stubs += 1;
                    assert!(
                        calls.is_empty(),
                        "export `{name}` should have called a stub but called {called:?}"
                    );
                    match stub {
                        Stub::Trap => assert!(
                            result.is_err(),
                            "export `{name}` should have called a trapping stub"
                        ),
                        Stub::DefaultValue => {
                            if let Err(e) = result {
                                panic!("failed to call export `{name}`: {e:?}");
                            }
                            let defaults = ty
                                .results()
                                .map(|ty| ty.default_value(&mut *store).unwrap())
                                .collect::<Vec<_>>();
                            assert_eq!(
                                actual, defaults,
                                "wrong default results from export `{name}`"
                            );
                        }
                    }
                    // Further calls aren't guaranteed to work after a trap.
                    if let Stub::Trap = stub {
                        break;
                    }
                }
            }

            if import_item.implements.is_some() {
                calls_through_labels += 1;
            }
        }
        Ok((calls_through_labels, calls_to_stubs))
    }
}

/// The kinds of stubs `Linker::define_unknown_imports_as_*` define.
#[derive(Clone, Copy, Debug)]
enum Stub {
    Trap,
    DefaultValue,
}

/// Returns whether calls to the WIT functions `a` and `b` can be forwarded to
/// one another, which requires them to have the same types.
fn funcs_eq(resolve: &Resolve, a: &WitFunction, b: &WitFunction) -> bool {
    a.params.len() == b.params.len()
        && a.params
            .iter()
            .zip(&b.params)
            .all(|(a, b)| types_eq(resolve, &a.ty, &b.ty))
        && match (&a.result, &b.result) {
            (None, None) => true,
            (Some(a), Some(b)) => types_eq(resolve, a, b),
            _ => false,
        }
}

/// Returns whether `a` and `b` are structurally the same types, with the same
/// names of fields, cases, etc. so that their `Val`s are the same.
///
/// Types containing resources aren't considered equal to anything as they're
/// not forwarded at this time.
fn types_eq(resolve: &Resolve, a: &Type, b: &Type) -> bool {
    fn dealias_ty(resolve: &Resolve, ty: Type) -> Type {
        match ty {
            Type::Id(id) => match resolve.types[dealias(resolve, id)].kind {
                TypeDefKind::Type(ty) => ty,
                _ => Type::Id(dealias(resolve, id)),
            },
            ty => ty,
        }
    }
    let opt_eq = |a: &Option<Type>, b: &Option<Type>| match (a, b) {
        (None, None) => true,
        (Some(a), Some(b)) => types_eq(resolve, a, b),
        _ => false,
    };

    match (dealias_ty(resolve, *a), dealias_ty(resolve, *b)) {
        (Type::Id(a), Type::Id(b)) => match (&resolve.types[a].kind, &resolve.types[b].kind) {
            (TypeDefKind::Record(a), TypeDefKind::Record(b)) => {
                a.fields.len() == b.fields.len()
                    && a.fields
                        .iter()
                        .zip(&b.fields)
                        .all(|(a, b)| a.name == b.name && types_eq(resolve, &a.ty, &b.ty))
            }
            (TypeDefKind::Tuple(a), TypeDefKind::Tuple(b)) => {
                a.types.len() == b.types.len()
                    && a.types
                        .iter()
                        .zip(&b.types)
                        .all(|(a, b)| types_eq(resolve, a, b))
            }
            (TypeDefKind::Flags(a), TypeDefKind::Flags(b)) => a
                .flags
                .iter()
                .map(|f| &f.name)
                .eq(b.flags.iter().map(|f| &f.name)),
            (TypeDefKind::Enum(a), TypeDefKind::Enum(b)) => a
                .cases
                .iter()
                .map(|c| &c.name)
                .eq(b.cases.iter().map(|c| &c.name)),
            (TypeDefKind::Variant(a), TypeDefKind::Variant(b)) => {
                a.cases.len() == b.cases.len()
                    && a.cases
                        .iter()
                        .zip(&b.cases)
                        .all(|(a, b)| a.name == b.name && opt_eq(&a.ty, &b.ty))
            }
            (TypeDefKind::Option(a), TypeDefKind::Option(b))
            | (TypeDefKind::List(a), TypeDefKind::List(b)) => types_eq(resolve, a, b),
            (TypeDefKind::Result(a), TypeDefKind::Result(b)) => {
                opt_eq(&a.ok, &b.ok) && opt_eq(&a.err, &b.err)
            }
            _ => false,
        },
        (Type::Id(_), _) | (_, Type::Id(_)) | (Type::ErrorContext, _) => false,
        (a, b) => a == b,
    }
}

/// Returns whether an export with the signature `export` can forward its
/// arguments to an import with the signature `import`, which is the case for
/// functions of the same type.
fn sigs_compatible(export: &WasmSignature, import: &WasmSignature) -> bool {
    let import_params = &import.params[..import.params.len() - usize::from(import.retptr)];
    export.retptr == import.retptr
        && export.indirect_params == import.indirect_params
        && core_types(&export.params) == core_types(import_params)
        && (export.retptr || core_types(&export.results) == core_types(&import.results))
}

fn core_types(tys: &[WasmType]) -> Vec<ValType> {
    tys.iter()
        .map(|ty| match ty {
            WasmType::I32 | WasmType::Pointer | WasmType::Length => ValType::I32,
            WasmType::I64 | WasmType::PointerOrI64 => ValType::I64,
            WasmType::F32 => ValType::F32,
            WasmType::F64 => ValType::F64,
        })
        .collect()
}

/// The body of an exported function with signature `export` which forwards its
/// arguments to the imported function `import` with signature `import_sig`.
///
/// If the import uses a return pointer, then a return area of size and
/// alignment `retarea` is allocated with `realloc` and returned.
fn forwarder_body(
    export: &WasmSignature,
    import: u32,
    import_sig: &WasmSignature,
    retarea: Option<(usize, usize)>,
    realloc: u32,
) -> Function {
    let nparams = u32::try_from(export.params.len()).unwrap();
    let mut f = Function::new(if import_sig.retptr {
        vec![(1, ValType::I32)]
    } else {
        vec![]
    });
    let mut ins = f.instructions();
    for i in 0..nparams {
        ins.local_get(i);
    }
    if import_sig.retptr {
        let (size, align) = retarea.unwrap();
        ins.i32_const(0)
            .i32_const(0)
            .i32_const(i32::try_from(align).unwrap())
            .i32_const(i32::try_from(size).unwrap())
            .call(realloc)
            .local_tee(nparams);
    }
    ins.call(import);
    if import_sig.retptr {
        ins.local_get(nparams);
    }
    ins.end();
    f
}

/// The body of a bump allocator used as `cabi_realloc`, which never frees
/// memory and grows memory as needed.
fn realloc_body() -> Function {
    // Parameters are `old_ptr`, `old_size`, `align` and `new_size`, followed
    // by the locals `ptr` and `end`.
    let mut f = Function::new([(2, ValType::I32)]);
    f.instructions()
        // ptr = (heap + align - 1) & -align
        .global_get(0)
        .local_get(2)
        .i32_add()
        .i32_const(1)
        .i32_sub()
        .i32_const(0)
        .local_get(2)
        .i32_sub()
        .i32_and()
        .local_tee(4)
        // heap = end = ptr + new_size
        .local_get(3)
        .i32_add()
        .local_tee(5)
        .global_set(0)
        // Grow memory if `end` is out of bounds.
        .local_get(5)
        .memory_size(0)
        .i32_const(16)
        .i32_shl()
        .i32_gt_u()
        .if_(wasm_encoder::BlockType::Empty)
        .local_get(5)
        .memory_size(0)
        .i32_const(16)
        .i32_shl()
        .i32_sub()
        .i32_const(0xffff)
        .i32_add()
        .i32_const(16)
        .i32_shr_u()
        .memory_grow(0)
        .i32_const(-1)
        .i32_eq()
        .if_(wasm_encoder::BlockType::Empty)
        .unreachable()
        .end()
        .end()
        .local_get(4)
        .end();
    f
}

fn unreachable_body() -> Function {
    let mut f = Function::new([]);
    f.instructions().unreachable().end();
    f
}

fn empty_body() -> Function {
    let mut f = Function::new([]);
    f.instructions().end();
    f
}

/// A small builder for core wasm modules.
#[derive(Default)]
struct CoreModule {
    types: TypeSection,
    type_indices: HashMap<(Vec<ValType>, Vec<ValType>), u32>,
    imports: ImportSection,
    num_imports: u32,
    funcs: FunctionSection,
    code: CodeSection,
    exports: ExportSection,
    num_funcs: u32,
}

impl CoreModule {
    fn ty(&mut self, params: &[WasmType], results: &[WasmType]) -> u32 {
        let key = (core_types(params), core_types(results));
        let next = u32::try_from(self.type_indices.len()).unwrap();
        *self.type_indices.entry(key.clone()).or_insert_with(|| {
            self.types.ty().function(key.0, key.1);
            next
        })
    }

    fn import(
        &mut self,
        module: &str,
        name: &str,
        params: &[WasmType],
        results: &[WasmType],
    ) -> u32 {
        assert_eq!(self.num_funcs, 0, "imports must come before definitions");
        let ty = self.ty(params, results);
        self.imports.import(module, name, EntityType::Function(ty));
        self.num_imports += 1;
        self.num_imports - 1
    }

    fn define(
        &mut self,
        params: &[WasmType],
        results: &[WasmType],
        body: Function,
        export: Option<&str>,
    ) -> u32 {
        let ty = self.ty(params, results);
        self.funcs.function(ty);
        self.code.function(&body);
        let index = self.num_imports + self.num_funcs;
        self.num_funcs += 1;
        if let Some(name) = export {
            self.exports.export(name, ExportKind::Func, index);
        }
        index
    }

    fn finish(mut self, memory: &str) -> Vec<u8> {
        let mut memories = MemorySection::new();
        memories.memory(MemoryType {
            minimum: 1,
            maximum: None,
            memory64: false,
            shared: false,
            page_size_log2: None,
        });
        self.exports.export(memory, ExportKind::Memory, 0);
        let mut globals = GlobalSection::new();
        globals.global(
            GlobalType {
                val_type: ValType::I32,
                mutable: true,
                shared: false,
            },
            &ConstExpr::i32_const(16),
        );

        let mut module = Module::new();
        module
            .section(&self.types)
            .section(&self.imports)
            .section(&self.funcs)
            .section(&memories)
            .section(&globals)
            .section(&self.exports)
            .section(&self.code);
        module.finish()
    }
}

/// Turns the core module `module` implementing the world of `model` into a
/// component, returning `None` if `wit-component` fails to do so.
fn componentize(model: &Model<'_>, module: &[u8], debug_names: bool) -> Option<Vec<u8>> {
    let mut module = module.to_vec();
    let result = wit_component::embed_component_metadata(
        &mut module,
        model.resolve,
        model.world,
        StringEncoding::UTF8,
        model.canonical_names,
    )
    .and_then(|()| {
        ComponentEncoder::default()
            .module(&module)?
            .validate(true)
            .emit_canonical_names(model.canonical_names)
            .debug_names(debug_names)
            .encode()
    });
    match result {
        Ok(wasm) => Some(wasm),
        Err(e) => {
            log::debug!("failed to create component: {e:?}");
            None
        }
    }
}

/// Returns a permutation of the labels under which the component `wasm`
/// imports the same interface with the same type, as a map from the name of
/// an import of `wasm` to the name of the import of the component wrapping it
/// which is passed for it.
fn permute_labels(
    u: &mut Unstructured<'_>,
    model: &Model<'_>,
    wasm: &[u8],
) -> arbitrary::Result<HashMap<String, String>> {
    use wasmparser::component_types::ComponentEntityType;

    // Labels of the same interface may have different types, for example
    // `wit-component` only imports resources which are used, so group labels
    // by interface and by the names of the exports of their type.
    let types = wasmparser::Validator::new_with_features(wasmparser::WasmFeatures::all())
        .validate_all(wasm)
        .unwrap();
    let mut labels: HashMap<(InterfaceId, Vec<&str>), Vec<&str>> = HashMap::new();
    for import in &model.imports {
        let Some((iface, _)) = &import.implements else {
            continue;
        };
        let Some(item) = types.component_item_for_import(&import.name) else {
            continue;
        };
        let ComponentEntityType::Instance(id) = item.ty else {
            unreachable!()
        };
        let mut exports = types[id]
            .exports
            .keys()
            .map(|s| s.as_str())
            .collect::<Vec<_>>();
        exports.sort();
        labels
            .entry((*iface, exports))
            .or_default()
            .push(&import.name);
    }

    let mut args = HashMap::new();
    for names in labels.values() {
        if names.len() < 2 || !u.arbitrary()? {
            continue;
        }
        let mut permuted = names.clone();
        for i in (1..permuted.len()).rev() {
            let j = u.int_in_range(0..=i)?;
            permuted.swap(i, j);
        }
        for (name, arg) in names.iter().zip(permuted) {
            args.insert(name.to_string(), arg.to_string());
        }
    }
    Ok(args)
}

/// Wraps the component `inner` in a component with the same imports and
/// exports, which instantiates `inner` and re-exports all of its exports.
///
/// The import `name` of `inner` is instantiated with the import named
/// `args[name]` of the outer component, or `name` if `args` doesn't have it.
fn wrap(inner: &[u8], args: &HashMap<String, String>) -> Vec<u8> {
    use wasm_encoder::{
        Alias, ComponentAliasSection, ComponentExportKind, ComponentExportSection,
        ComponentInstanceSection, ComponentSectionId, RawSection,
    };
    use wasmparser::{
        ComponentAlias, ComponentExternalKind, ComponentOuterAliasKind, ComponentTypeRef, Parser,
        Payload,
    };

    /// The number of items defined so far in each index space.
    #[derive(Default)]
    struct Counts {
        modules: u32,
        funcs: u32,
        values: u32,
        types: u32,
        instances: u32,
        components: u32,
    }

    impl Counts {
        /// Adds an item of kind `kind`, returning its index.
        fn push(&mut self, kind: ComponentExportKind) -> u32 {
            let count = match kind {
                ComponentExportKind::Module => &mut self.modules,
                ComponentExportKind::Func => &mut self.funcs,
                ComponentExportKind::Value => &mut self.values,
                ComponentExportKind::Type => &mut self.types,
                ComponentExportKind::Instance => &mut self.instances,
                ComponentExportKind::Component => &mut self.components,
            };
            *count += 1;
            *count - 1
        }
    }

    fn export_kind(kind: ComponentExternalKind) -> ComponentExportKind {
        match kind {
            ComponentExternalKind::Module => ComponentExportKind::Module,
            ComponentExternalKind::Func => ComponentExportKind::Func,
            ComponentExternalKind::Value => ComponentExportKind::Value,
            ComponentExternalKind::Type => ComponentExportKind::Type,
            ComponentExternalKind::Instance => ComponentExportKind::Instance,
            ComponentExternalKind::Component => ComponentExportKind::Component,
        }
    }

    // Copy the types, imports and aliases of `inner`, which `wit-component`
    // all puts at the start of the component before anything else, to the
    // outer component to get the same imports in the same index spaces.
    let mut outer = wasm_encoder::Component::new();
    let mut counts = Counts::default();
    let mut imports = Vec::new();
    let mut exports = Vec::new();
    let mut prefix = true;
    let mut depth = 0;
    for payload in Parser::new(0).parse_all(inner) {
        let payload = payload.unwrap();
        match payload {
            Payload::Version { .. } => depth += 1,
            Payload::End(_) => depth -= 1,
            _ if depth > 1 => {}
            Payload::ComponentTypeSection(_)
            | Payload::CoreTypeSection(_)
            | Payload::ComponentImportSection(_)
            | Payload::ComponentAliasSection(_)
                if prefix =>
            {
                let (id, range) = payload.as_section().unwrap();
                let range =
                    usize::try_from(range.start).unwrap()..usize::try_from(range.end).unwrap();
                outer.section(&RawSection {
                    id,
                    data: &inner[range],
                });
                match payload {
                    Payload::ComponentTypeSection(reader) => counts.types += reader.count(),
                    Payload::ComponentImportSection(reader) => {
                        for import in reader {
                            let import = import.unwrap();
                            let kind = match import.ty {
                                ComponentTypeRef::Module(_) => ComponentExportKind::Module,
                                ComponentTypeRef::Func(_) => ComponentExportKind::Func,
                                ComponentTypeRef::Value(_) => ComponentExportKind::Value,
                                ComponentTypeRef::Type(_) => ComponentExportKind::Type,
                                ComponentTypeRef::Instance(_) => ComponentExportKind::Instance,
                                ComponentTypeRef::Component(_) => ComponentExportKind::Component,
                            };
                            imports.push((import.name.name, kind, counts.push(kind)));
                        }
                    }
                    Payload::ComponentAliasSection(reader) => {
                        for alias in reader {
                            match alias.unwrap() {
                                ComponentAlias::InstanceExport { kind, .. } => {
                                    counts.push(export_kind(kind));
                                }
                                ComponentAlias::Outer { kind, .. } => match kind {
                                    ComponentOuterAliasKind::CoreModule => {
                                        counts.push(ComponentExportKind::Module);
                                    }
                                    ComponentOuterAliasKind::Type => {
                                        counts.push(ComponentExportKind::Type);
                                    }
                                    ComponentOuterAliasKind::Component => {
                                        counts.push(ComponentExportKind::Component);
                                    }
                                    ComponentOuterAliasKind::CoreType => {}
                                },
                                ComponentAlias::CoreInstanceExport { .. } => {}
                            }
                        }
                    }
                    _ => {}
                }
            }
            Payload::ComponentImportSection(_) => {
                panic!("imports of components created by `wit-component` should come first")
            }
            Payload::ComponentExportSection(reader) => {
                prefix = false;
                for export in reader {
                    exports.push(export.unwrap());
                }
            }
            Payload::CustomSection(_) => {}
            _ => prefix = false,
        }
    }

    // Instantiate `inner` with the imports of the outer component.
    outer.section(&RawSection {
        id: ComponentSectionId::Component.into(),
        data: inner,
    });
    let component = counts.push(ComponentExportKind::Component);
    let mut instances = ComponentInstanceSection::new();
    instances.instantiate(
        component,
        imports
            .iter()
            .map(|(name, ..)| {
                let arg = args.get(*name).map_or(*name, |s| s.as_str());
                let (_, kind, index) = imports.iter().find(|(n, ..)| *n == arg).unwrap();
                (*name, *kind, *index)
            })
            .collect::<Vec<_>>(),
    );
    outer.section(&instances);
    let instance = counts.push(ComponentExportKind::Instance);

    // Re-export all the exports of the instance with the same names.
    let mut aliases = ComponentAliasSection::new();
    let mut outer_exports = ComponentExportSection::new();
    for export in &exports {
        let kind = export_kind(export.kind);
        aliases.alias(Alias::InstanceExport {
            instance,
            kind,
            name: export.name.name,
        });
        outer_exports.export(
            wasm_encoder::ComponentExternName {
                name: export.name.name.into(),
                implements: export.name.implements.map(Into::into),
                version_suffix: export.name.version_suffix.map(Into::into),
                external_id: export.name.external_id.map(Into::into),
            },
            kind,
            counts.push(kind),
            None,
        );
    }
    outer.section(&aliases);
    outer.section(&outer_exports);
    let wasm = outer.finish();

    if let Err(e) = wasmparser::Validator::new_with_features(wasmparser::WasmFeatures::all())
        .validate_all(&wasm)
    {
        log_wasm(inner);
        log_wasm(&wasm);
        panic!("wrapped component is invalid: {e:?}");
    }
    wasm
}

/// Creates the engine to test with.
fn engine(
    u: &mut Unstructured<'_>,
    config: &mut generators::Config,
    canonical_names: bool,
) -> arbitrary::Result<Engine> {
    config.module_config.component_model_implements = true;
    config.module_config.component_model_canonical_names = canonical_names || u.arbitrary()?;
    config.module_config.config.multi_value_enabled = true;
    config.module_config.config.bulk_memory_enabled = true;
    config.module_config.config.reference_types_enabled = true;
    if config.wasmtime.compiler_strategy == CompilerStrategy::Winch {
        config.wasmtime.compiler_strategy = CompilerStrategy::CraneliftNative;
    }

    // Make sure the pooling allocator, if used, can instantiate the
    // components generated here.
    const MEMORY_SIZE: usize = 1 << 20;
    if let InstanceAllocationStrategy::Pooling(p) = &mut config.wasmtime.strategy {
        p.total_component_instances = p.total_component_instances.max(1);
        p.total_core_instances = p.total_core_instances.max(4);
        p.total_memories = p.total_memories.max(1);
        p.total_tables = p.total_tables.max(2);
        p.max_memories_per_component = p.max_memories_per_component.max(1);
        p.max_tables_per_component = p.max_tables_per_component.max(2);
        p.max_memories_per_module = p.max_memories_per_module.max(1);
        p.max_tables_per_module = p.max_tables_per_module.max(1);
        p.table_elements = p.table_elements.max(1000);
        p.component_instance_size = p.component_instance_size.max(1 << 20);
        p.core_instance_size = p.core_instance_size.max(1 << 20);
        p.max_memory_size = p.max_memory_size.max(MEMORY_SIZE);
        p.memory_protection_keys = Enabled::No;
    }
    if let Some(reservation) = &mut config.wasmtime.memory_config.memory_reservation {
        *reservation = (*reservation).max(MEMORY_SIZE as u64);
    }
    config.wasmtime.make_internally_consistent();

    Ok(Engine::new(&config.to_wasmtime()).unwrap())
}

/// The state of the store used to instantiate components.
#[derive(Default)]
struct HostState {
    /// Calls made to imported functions, identified by their index in
    /// `Model::import_funcs`, along with their arguments.
    calls: Vec<(usize, Vec<Val>)>,
    /// The results to return from the next call to an imported function.
    results: Option<Vec<Val>>,
}

/// Definitions of the imports of a world in a `Linker`.
struct Host<'a> {
    model: &'a Model<'a>,
    /// The host resource types, identified by their payload in
    /// `ResourceType::host_dynamic`, for each resource imported by the world.
    ///
    /// Resources are identified by the import defining them, `None` for the
    /// root of the world, and their definition in WIT. All labels importing
    /// the same interface get distinct resources, and interfaces using types
    /// from other interfaces use the resources of the import of that
    /// interface by its own name.
    payloads: HashMap<(Option<WorldKey>, TypeId), u32>,
}

impl<'a> Host<'a> {
    fn new(model: &'a Model<'a>) -> Self {
        let resolve = model.resolve;
        let mut payloads = HashMap::new();
        for import in &model.imports {
            let (interface, types) = match import.item {
                WorldItem::Interface { id, .. } => (
                    Some((import.key, *id)),
                    resolve.interfaces[*id].types.values().copied().collect(),
                ),
                WorldItem::Type { id, .. } => (None, vec![*id]),
                WorldItem::Function(_) => continue,
            };
            for ty in types {
                if let Some(key) = resource_key(resolve, interface, ty) {
                    let next = u32::try_from(payloads.len()).unwrap();
                    payloads.entry(key).or_insert(next);
                }
            }
        }
        Host { model, payloads }
    }

    /// Returns the resource type defined for `ty` in the import `interface`.
    fn resource(
        &self,
        interface: Option<(&WorldKey, InterfaceId)>,
        ty: TypeId,
    ) -> Option<ResourceType> {
        let key = resource_key(self.model.resolve, interface, ty)?;
        Some(ResourceType::host_dynamic(self.payloads[&key]))
    }

    /// Creates a linker defining all imports of the world, except `skip`.
    ///
    /// If `alias` is set and `skip` is an import implementing an interface,
    /// then the definitions for `skip` are defined under the name of that
    /// interface instead.
    fn linker(
        &self,
        engine: &Engine,
        skip: Option<&str>,
        alias: bool,
    ) -> wasmtime::Result<Linker<HostState>> {
        let model = self.model;
        let resolve = model.resolve;
        let mut linker = Linker::new(engine);
        linker.allow_shadowing(alias);

        for (i, f) in model.import_funcs.iter().enumerate() {
            if f.key.is_none() && Some(f.func.name.as_str()) != skip {
                define_host_func(&mut linker.root(), &f.func.name, i)?;
            }
        }

        for import in &model.imports {
            let skipped = Some(import.name.as_str()) == skip;
            match import.item {
                WorldItem::Interface { id, .. } => {
                    let name = match (&import.implements, skipped) {
                        (_, false) => import.name.as_str(),
                        (Some((_, implements)), true) if alias => implements.as_str(),
                        (_, true) => continue,
                    };
                    let mut instance = linker.instance(name)?;
                    for (i, f) in model.import_funcs.iter().enumerate() {
                        if f.key == Some(import.key) {
                            define_host_func(&mut instance, &f.func.name, i)?;
                        }
                    }
                    for (ty_name, ty) in resolve.interfaces[*id].types.iter() {
                        if let Some(rt) = self.resource(Some((import.key, *id)), *ty) {
                            instance.resource(ty_name, rt, |_, _| Ok(()))?;
                        }
                    }
                }
                WorldItem::Type { id, .. } if !skipped => {
                    if let Some(rt) = self.resource(None, *id) {
                        linker.root().resource(&import.name, rt, |_, _| Ok(()))?;
                    }
                }
                WorldItem::Type { .. } | WorldItem::Function(_) => {}
            }
        }
        Ok(linker)
    }

    /// Checks that the resources imported by `component`, as seen through
    /// `Linker::substituted_component_type`, are those defined in the linker.
    fn check_substituted_type(
        &self,
        engine: &Engine,
        linker: &Linker<HostState>,
        component: &Component,
    ) {
        let ty = linker.substituted_component_type(component).unwrap();
        for (name, ext) in ty.imports(engine) {
            let import = self.model.import(name).unwrap();
            assert_eq!(
                ext.implements,
                import.implements.as_ref().map(|(_, s)| s.as_str()),
                "wrong `implements` for substituted import `{name}`"
            );
            assert_eq!(
                ext.external_id, import.external_id,
                "wrong `external-id` for substituted import `{name}`"
            );
            match (&ext.ty, import.item) {
                (ComponentItem::ComponentInstance(instance), WorldItem::Interface { id, .. }) => {
                    for (ty_name, ext) in instance.exports(engine) {
                        let ComponentItem::Resource(rt) = ext.ty else {
                            continue;
                        };
                        let ty = self.model.resolve.interfaces[*id].types[ty_name];
                        assert_eq!(
                            Some(rt),
                            self.resource(Some((import.key, *id)), ty),
                            "wrong resource type for import `{name}#{ty_name}`"
                        );
                    }
                }
                (ComponentItem::Resource(rt), WorldItem::Type { id, .. }) => {
                    assert_eq!(
                        Some(*rt),
                        self.resource(None, *id),
                        "wrong resource type for import `{name}`"
                    );
                }
                _ => {}
            }
        }
    }

    /// Checks that `component` can't be instantiated by a linker missing one
    /// of its imports.
    fn check_missing_import(
        &self,
        u: &mut Unstructured<'_>,
        engine: &Engine,
        component: &Component,
    ) -> arbitrary::Result<()> {
        if !u.arbitrary()? {
            return Ok(());
        }
        // Only consider imports which need a definition: functions, resources
        // which aren't aliases of other resources (which are imported with an
        // `(eq ...)` bound), and instances with any of those.
        let resolve = self.model.resolve;
        let is_resource_definition =
            |ty: TypeId| matches!(resolve.types[ty].kind, TypeDefKind::Resource);
        let ty = component.component_type();
        let candidates = ty
            .imports(engine)
            .filter(|(name, ext)| {
                let import = self.model.import(name).unwrap();
                match (&ext.ty, import.item) {
                    (
                        ComponentItem::ComponentInstance(instance),
                        WorldItem::Interface { id, .. },
                    ) => instance.exports(engine).any(|(name, ext)| match ext.ty {
                        ComponentItem::Resource(_) => {
                            is_resource_definition(resolve.interfaces[*id].types[name])
                        }
                        ComponentItem::Type(_) => false,
                        _ => true,
                    }),
                    (ComponentItem::Resource(_), WorldItem::Type { id, .. }) => {
                        is_resource_definition(*id)
                    }
                    (ComponentItem::Type(_), _) => false,
                    _ => true,
                }
            })
            .map(|(name, _)| name.to_string())
            .collect::<Vec<_>>();
        if candidates.is_empty() {
            return Ok(());
        }
        let skip = u.choose(&candidates)?;
        let alias = u.arbitrary()?;
        let linker = self.linker(engine, Some(skip), alias).unwrap();
        if linker.instantiate_pre(component).is_ok() {
            panic!(
                "component was instantiated without a definition of `{skip}` \
                 (defined under the name of the interface it implements: {alias})"
            );
        }
        Ok(())
    }

    /// Checks that when one of the imports isn't defined in the linker but
    /// stubbed with `Linker::define_unknown_imports_as_*` instead, calls which
    /// go through that import reach the stub while all other calls still reach
    /// the definitions of their own import.
    ///
    /// Returns the number of calls which went to a stub.
    fn check_unknown_imports(
        &self,
        u: &mut Unstructured<'_>,
        config: &generators::Config,
        engine: &Engine,
        component: &Component,
        guest: &Guest<'_>,
    ) -> arbitrary::Result<usize> {
        if !u.ratio(1, 4)? {
            return Ok(0);
        }
        // Stubs define fresh resources which would mismatch the resources
        // defined in the linker for other imports using them, so only stub
        // out imports whose resources, if any, can't be used elsewhere.
        let resolve = self.model.resolve;
        let ty = component.component_type();
        let candidates = self
            .model
            .imports
            .iter()
            .filter(|i| ty.get_import(engine, &i.name).is_some())
            .filter(|i| match i.item {
                WorldItem::Function(_) => true,
                WorldItem::Interface { id, .. } => {
                    matches!(i.key, WorldKey::Name(_))
                        || !resolve.interfaces[*id]
                            .types
                            .values()
                            .any(|ty| matches!(resolve.types[*ty].kind, TypeDefKind::Resource))
                }
                WorldItem::Type { .. } => false,
            })
            .collect::<Vec<_>>();
        if candidates.is_empty() {
            return Ok(0);
        }
        let stubbed = u.choose(&candidates)?;
        let stub = if u.arbitrary()? {
            Stub::Trap
        } else {
            Stub::DefaultValue
        };

        let mut store = Store::new(engine, HostState::default());
        config.configure_store_epoch_and_fuel(&mut store);
        let mut linker = self.linker(engine, Some(&stubbed.name), false).unwrap();
        match stub {
            Stub::Trap => linker.define_unknown_imports_as_traps(component).unwrap(),
            Stub::DefaultValue => linker
                .define_unknown_imports_as_default_values(&mut store, component)
                .unwrap(),
        }
        let instance = match linker.instantiate(&mut store, component) {
            Ok(instance) => instance,
            Err(e) => panic!(
                "failed to instantiate component with `{}` stubbed: {e:?}",
                stubbed.name
            ),
        };
        let (_, calls_to_stubs) = guest.call_forwarders(
            u,
            &mut store,
            &instance,
            self.model,
            Some((&stubbed.name, stub)),
        )?;
        Ok(calls_to_stubs)
    }
}

/// Returns the key under which `Host::payloads` records the resource that
/// `ty`, imported through `interface`, refers to, or `None` if `ty` isn't a
/// resource.
fn resource_key(
    resolve: &Resolve,
    interface: Option<(&WorldKey, InterfaceId)>,
    ty: TypeId,
) -> Option<(Option<WorldKey>, TypeId)> {
    let root = dealias(resolve, ty);
    if !matches!(resolve.types[root].kind, TypeDefKind::Resource) {
        return None;
    }
    let import = match resolve.types[root].owner {
        TypeOwner::Interface(owner) => match interface {
            Some((key, id)) if id == owner => Some(key.clone()),
            _ => Some(WorldKey::Interface(owner)),
        },
        TypeOwner::World(_) => None,
        TypeOwner::None => return None,
    };
    Some((import, root))
}

/// Defines `name` in `instance` as a host function for the import function
/// `index` in `Model::import_funcs`.
fn define_host_func(
    instance: &mut LinkerInstance<'_, HostState>,
    name: &str,
    index: usize,
) -> wasmtime::Result<()> {
    instance.func_new(name, move |mut store, _ty, params, results| {
        let state = store.data_mut();
        state.calls.push((index, params.to_vec()));
        let Some(vals) = state.results.take() else {
            wasmtime::bail!("unexpected call to import function {index}");
        };
        results.clone_from_slice(&vals);
        Ok(())
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test::gen_until_pass;

    // Test that this fuzzer eventually generates the interesting cases it's
    // meant to generate, to prevent it from silently not fuzzing much.
    #[test]
    fn eventually_explores_labels() {
        let mut total = Stats::default();
        let ok = gen_until_pass(|(), u| {
            if let Ok(stats) = run(u) {
                total.labelled_imports += stats.labelled_imports;
                total.labelled_exports += stats.labelled_exports;
                total.external_ids += stats.external_ids;
                total.resources += stats.resources;
                total.exported_resources += stats.exported_resources;
                total.calls_through_labels += stats.calls_through_labels;
                total.calls_to_stubs += stats.calls_to_stubs;
                total.wrapped |= stats.wrapped;
            }
            Ok(total.labelled_imports > 0
                && total.labelled_exports > 0
                && total.external_ids > 0
                && total.resources > 0
                && total.exported_resources > 0
                && total.calls_through_labels > 0
                && total.calls_to_stubs > 0
                && total.wrapped)
        });
        assert!(ok, "never explored all interesting cases: {total:?}");
    }
}
