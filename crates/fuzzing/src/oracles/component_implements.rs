//! Oracle for the component model `implements` and `external-id` name
//! annotations (🏷️).
//!
//! Unlike the `component_api` fuzzer, which stresses the shapes of *values*
//! flowing in and out of a fixed component, this fuzzer stresses the shapes of
//! *components*: which interfaces are imported and exported, under which names
//! and with which annotations. Each test case is built as follows:
//!
//! 1. `wit-smith` generates a set of WIT packages, which contain interfaces
//!    with functions, resources, `use`s of types from other interfaces,
//!    versions, etc. A world is then picked from these packages (`wit-smith`
//!    itself generates labelled imports and exports) or, more often, generated
//!    here from the available interfaces. Worlds generated here import and
//!    export interfaces both by their own name and under any number of labels,
//!    e.g. `import a: x:y/z; import b: x:y/z; export c: x:y/z;`, which are
//!    encoded as `(implements "x:y/z")` names. Every item of the world and
//!    every function and type of every interface then gets a distinct random
//!    `external-id`, or none at all.
//!
//! 2. A core module is generated for that world and turned into a component
//!    with `wit-component`, optionally with canonical interface names. Most
//!    exported functions forward their arguments to an imported function of
//!    the same type, chosen at random among all imported functions, in
//!    particular among all the labels which import the same interface. The
//!    component is optionally nested within another component with the same
//!    imports and exports, which instantiates it, possibly passing the imports
//!    for some labels of an interface to other labels of the same interface,
//!    and re-exports all of its exports.
//!
//! 3. The component is compiled with Wasmtime and its reflection is checked
//!    against the WIT: the names, kinds, `implements` and `external-id` of all
//!    imports and exports and of the exports of imported and exported
//!    instances, `ComponentExtern::is_implements` for a few interface names
//!    and versions, and `Component::get_export{,_index}`. This is checked again
//!    after a serialization round-trip.
//!
//! 4. Each import is defined in a `Linker` under its own name. Each imported
//!    function is a host function recording which import it is, and each
//!    imported resource gets a distinct host resource type. Resource types are
//!    checked through `Linker::substituted_component_type`, and a linker which
//!    is missing one of the imports, but which possibly defines it under the
//!    name of the interface it implements, must fail to instantiate the
//!    component. The component is then instantiated, its exports are checked,
//!    including the resource types of exported interfaces, and the forwarding
//!    exports are called with random arguments to check that each call goes
//!    through exactly the import it's wired to, with arguments and results
//!    unchanged. Finally, the component is optionally instantiated again with
//!    one of its imports stubbed out by `Linker::define_unknown_imports_as_*`,
//!    checking that only the calls going through that import reach the stub.

